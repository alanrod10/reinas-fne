function baseEvidence(r, level){
  return {
    identity:r.name?3:null,
    year:3,
    province:level==='national'?(r.province?3:null):null,
    school:level==='jujuy-provincial'?(r.school?3:null):null,
    department:level==='jujuy-provincial'?(r.department?3:null):null,
    event:3,
    image:0,
    verifiedFields:[],unconfirmedFields:[]
  };
}
function rec(id,year,name,variants,province,status,title,sourceIds){
  const r={id,year,level:'national',name,variants,province,status,titleOfficial:title,sourceIds,imageIds:[],notes:[]};
  r.evidence=baseEvidence(r,'national');
  if(!name && status!=='no-election') r.evidence.unconfirmedFields.push('identity');
  return r;
}
function jrec(id,year,name,variants,school,department,locality,region,status,title,sourceIds,note){
  const r={id,year,level:'jujuy-provincial',name,variants,school,department,locality,region,status,titleOfficial:title,sourceIds,imageIds:[],notes:note?[note]:[]};
  r.evidence=baseEvidence(r,'jujuy-provincial');
  if(!school && status!=='no-election') r.evidence.unconfirmedFields.push('school');
  return r;
}
